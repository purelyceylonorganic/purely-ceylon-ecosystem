const normalize = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.,]/g, "")
    .trim()
    .toLowerCase();

const lookup = new Map<string, Country>();

for (const country of COUNTRIES) {
  lookup.set(normalize(country.name), country);
  lookup.set(normalize(country.code), country);
  for (const alias of country.aliases) {
    lookup.set(normalize(alias), country);
  }
}

// "uk" / "United Kingdom" / "USA" → சரியான Country; தெரியவில்லை என்றால் undefined
export function findCountry(input: string | null | undefined): Country | undefined {
  if (!input) return undefined;
  return lookup.get(normalize(input));
}

// Zone-ல் சேமிக்க: பெயரை நிலையான வடிவத்துக்கு மாற்றும்
export function canonicalCountryName(input: string): string {
  return findCountry(input)?.name ?? input.trim();
}